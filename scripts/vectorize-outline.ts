/**
 * Converts the outlined unicorn (supplied as a PNG embedded in an SVG, plus a ® mark that we drop)
 * into a crisp vector path. The art is axis-aligned pixel lines, so each line becomes a rectangle:
 * horizontal pixel runs per row are merged with identical runs on the rows below.
 *
 * Input:  assets/unicorn/unicorn-outline-source.png (extracted from "unosquare-unicorn outlined.svg")
 * Output: src/lib/unicornOutline.ts (path data + viewBox)
 * Run:    npx tsx scripts/vectorize-outline.ts   (then npm run assets:stamps)
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(__dirname, "..");

async function main() {
  const { data, info } = await sharp(path.join(root, "assets", "unicorn", "unicorn-outline-source.png"))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: W, height: H } = info;
  const on = (x: number, y: number) => data[(y * W + x) * 4 + 3] > 127;

  // Runs per row: "x0:x1" keys.
  type Rect = { x: number; y: number; w: number; h: number };
  const open = new Map<string, Rect>();
  const rects: Rect[] = [];
  for (let y = 0; y <= H; y++) {
    const runs = new Set<string>();
    if (y < H) {
      let start = -1;
      for (let x = 0; x <= W; x++) {
        const v = x < W && on(x, y);
        if (v && start < 0) start = x;
        if (!v && start >= 0) {
          runs.add(`${start}:${x}`);
          start = -1;
        }
      }
    }
    // Close rects whose run doesn't continue on this row.
    for (const [key, r] of open) {
      if (!runs.has(key)) {
        rects.push(r);
        open.delete(key);
      }
    }
    for (const key of runs) {
      const existing = open.get(key);
      if (existing) existing.h++;
      else {
        const [x0, x1] = key.split(":").map(Number);
        open.set(key, { x: x0, y, w: x1 - x0, h: 1 });
      }
    }
  }

  // Crop to the art's bounds.
  const minX = Math.min(...rects.map((r) => r.x));
  const minY = Math.min(...rects.map((r) => r.y));
  const maxX = Math.max(...rects.map((r) => r.x + r.w));
  const maxY = Math.max(...rects.map((r) => r.y + r.h));
  const d = rects.map((r) => `M${r.x - minX} ${r.y - minY}h${r.w}v${r.h}h${-r.w}z`).join("");
  const w = maxX - minX;
  const h = maxY - minY;

  const out = `/** Generated by scripts/vectorize-outline.ts from the outlined unicorn artwork (® removed). Do not edit. */
export const OUTLINE_PATH =
  "${d}";

/** Art bounds ${w}×${h}; the viewBox pads it into a square. */
export const OUTLINE_VIEWBOX = "${-Math.round((Math.max(w, h) - w) / 2 + 8)} ${-Math.round((Math.max(w, h) - h) / 2 + 8)} ${Math.max(w, h) + 16} ${Math.max(w, h) + 16}";
`;
  await fs.writeFile(path.join(root, "src", "lib", "unicornOutline.ts"), out);
  console.log(`${rects.length} rects, art ${w}×${h}, path ${d.length} chars`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
